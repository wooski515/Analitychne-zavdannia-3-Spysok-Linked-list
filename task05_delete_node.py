"""Задача 5. Видалити вузол зі списку, маючи доступ лише до цього вузла.

Голови списку в нас немає, тому попередній вузол знайти неможливо.
Замість цього копіюємо в node значення наступного вузла і "викидаємо"
наступний вузол зі списку. Це працює, бо node гарантовано не останній.
"""


def delete_node(node):
    """Видаляє значення node зі списку (node не є хвостом)."""
    node.val = node.next.val
    node.next = node.next.next
